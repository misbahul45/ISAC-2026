export type SoundComponent =
    | 'sound1'
    | 'sound2'
    | 'sound3'
    | 'sound4';

export type ResponsiveDistance = {
    base: number;
    sm: number;
    md: number;
    lg: number;
    xl: number;
};

export type FloatingIconVisibility = 'base' | 'sm' | 'md';

export type FloatingIconConfig = {
    component: SoundComponent;
    angle: number;
    distance: ResponsiveDistance;
    size: string;
    opacity: number;
    delay: number;
    phase: number;
    speed: number;
    orbitRadius: number;
    orbitSpeed: number;
    showFrom: FloatingIconVisibility;
};

const createResponsiveDistance = (
    desktopDistance: number,
): ResponsiveDistance => ({
    base: Math.min(Math.round(desktopDistance * 0.3), 170),
    sm: Math.round(desktopDistance * 0.44),
    md: Math.round(desktopDistance * 0.62),
    lg: Math.round(desktopDistance * 0.8),
    xl: desktopDistance,
});

const getVisibility = (
    desktopDistance: number,
): FloatingIconVisibility => {
    if (desktopDistance >= 550) {
        return 'md';
    }

    if (desktopDistance >= 500) {
        return 'sm';
    }

    return 'base';
};

const createIcon = (
    component: SoundComponent,
    angle: number,
    distance: number,
    size: string,
    opacity: number,
    delay: number,
    phase: number,
    speed: number,
    orbitRadius: number,
    orbitSpeed: number,
    showFrom = getVisibility(distance),
): FloatingIconConfig => ({
    component,
    angle,
    distance: createResponsiveDistance(distance),
    size,
    opacity,
    delay,
    phase,
    speed,
    orbitRadius,
    orbitSpeed,
    showFrom,
});

export const resolveResponsiveDistance = (
    distance: ResponsiveDistance,
    viewportWidth: number,
): number => {
    if (viewportWidth >= 1280) {
        return distance.xl;
    }

    if (viewportWidth >= 1024) {
        return distance.lg;
    }

    if (viewportWidth >= 768) {
        return distance.md;
    }

    if (viewportWidth >= 640) {
        return distance.sm;
    }

    return distance.base;
};

